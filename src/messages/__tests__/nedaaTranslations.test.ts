describe("nedaa translations", () => {
  it("keeps Nedaa translation keys identical in both locales", () => {
    expect(keysOf(ar.nedaa).sort()).toEqual(keysOf(en.nedaa).sort());
  });

  it("contains localized copy for shared UI tables, forms, and staff assignments", () => {
    for (const key of requiredNedaaKeys) {
      expect(getPath(en.nedaa, key), `en.nedaa.${key}`).toEqual(
        expect.any(String),
      );
      expect(getPath(ar.nedaa, key), `ar.nedaa.${key}`).toEqual(
        expect.any(String),
      );
    }
  });
});
